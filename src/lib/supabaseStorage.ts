export type PendingUploadKind = 'finished-drink' | 'suggested-product';
export type UploadProgressPhase =
  | 'idle'
  | 'validating'
  | 'uploading'
  | 'uploaded'
  | 'error';

export interface ImageFileValidationInput {
  mimeType: string;
  sizeBytes: number;
  width?: number;
  height?: number;
}

export interface ImageValidationResult {
  valid: boolean;
  error?: string;
}

/**
 * Pure validation for MIME type, file size (<= 5MB), and image dimensions (120px–6000px).
 */
export function validateImageFileMetadata(
  input: ImageFileValidationInput
): ImageValidationResult {
  if (
    !(ALLOWED_IMAGE_MIME_TYPES as readonly string[]).includes(input.mimeType)
  ) {
    return {
      valid: false,
      error: 'Unsupported format. Please upload a JPG, PNG, or WebP image.',
    };
  }

  if (!Number.isFinite(input.sizeBytes) || input.sizeBytes <= 0) {
    return {
      valid: false,
      error: 'Selected image file is empty or unreadable.',
    };
  }

  if (input.sizeBytes > MAX_IMAGE_FILE_SIZE_BYTES) {
    return {
      valid: false,
      error: `File size (${(input.sizeBytes / (1024 * 1024)).toFixed(
        1
      )}MB) exceeds the 5MB maximum limit.`,
    };
  }

  if (input.width !== undefined && input.height !== undefined) {
    if (
      !Number.isFinite(input.width) ||
      !Number.isFinite(input.height) ||
      input.width < MIN_IMAGE_DIMENSION_PX ||
      input.height < MIN_IMAGE_DIMENSION_PX
    ) {
      return {
        valid: false,
        error: `Image dimensions are too small. Minimum size is ${MIN_IMAGE_DIMENSION_PX}x${MIN_IMAGE_DIMENSION_PX} pixels.`,
      };
    }

    if (
      input.width > MAX_IMAGE_DIMENSION_PX ||
      input.height > MAX_IMAGE_DIMENSION_PX
    ) {
      return {
        valid: false,
        error: `Image dimensions exceed the maximum allowed ${MAX_IMAGE_DIMENSION_PX}x${MAX_IMAGE_DIMENSION_PX} pixels.`,
      };
    }
  }

  return { valid: true };
}

export function isInlineDataUrl(value: string | null | undefined): boolean {
  if (!value) return false;
  return value.trim().toLowerCase().startsWith('data:');
}

export function isRelativeStoragePath(value: string | null | undefined): boolean {
  if (!value) return false;
  const trimmed = value.trim();
  if (!trimmed || isInlineDataUrl(trimmed)) return false;
  if (
    trimmed.startsWith('http://') ||
    trimmed.startsWith('https://') ||
    trimmed.startsWith('/')
  ) {
    return false;
  }
  return !trimmed.includes('..');
}

function mimeTypeToExtension(mimeType: string): 'jpg' | 'png' | 'webp' {
  if (mimeType === 'image/png') return 'png';
  if (mimeType === 'image/webp') return 'webp';
  return 'jpg';
}

function generateRandomHex(byteLength = 16): string {
  const bytes = new Uint8Array(byteLength);
  if (typeof globalThis.crypto !== 'undefined' && globalThis.crypto.getRandomValues) {
    globalThis.crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < byteLength; i++) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

/**
 * Generates a safe, non-guessable, traversal-proof relative storage path
 * inside the private `pending-submissions` bucket. Never uses user filenames.
 */
export function buildPendingSubmissionStoragePath(
  kind: PendingUploadKind,
  mimeType: string,
  now = new Date()
): string {
  const datePrefix = now.toISOString().slice(0, 10);
  const ext = mimeTypeToExtension(mimeType);
  const token = generateRandomHex(16);
  return `${kind}/${datePrefix}/${token}.${ext}`;
}

export interface UploadPendingImageParams {
  blob: Blob;
  mimeType: string;
  sizeBytes: number;
  width?: number;
  height?: number;
  kind: PendingUploadKind;
  onProgress?: (phase: UploadProgressPhase) => void;
}

/**
 * Uploads a validated pending community submission image to the PRIVATE
 * `pending-submissions` bucket. Returns ONLY the relative storage path—
 * never a public URL and never an inline base64 data URL.
 */
export async function uploadPendingSubmissionImage(
  client: SupabaseClient | null,
  params: UploadPendingImageParams
): Promise<{ bucket: typeof STORAGE_BUCKETS.PENDING_SUBMISSIONS; storagePath: string }> {
  const db = requireSupabaseClient(client, 'uploadPendingSubmissionImage');

  params.onProgress?.('validating');
  const validation = validateImageFileMetadata({
    mimeType: params.mimeType,
    sizeBytes: params.sizeBytes,
    width: params.width,
    height: params.height,
  });

  if (!validation.valid) {
    params.onProgress?.('error');
    throw new SupabaseRepositoryError(
      'uploadPendingSubmissionImage',
      validation.error || 'Image validation failed.',
      { code: 'INVALID_IMAGE_FILE' }
    );
  }

  const storagePath = buildPendingSubmissionStoragePath(params.kind, params.mimeType);
  params.onProgress?.('uploading');

  const { data, error } = await db.storage
    .from(STORAGE_BUCKETS.PENDING_SUBMISSIONS)
    .upload(storagePath, params.blob, {
      contentType: params.mimeType,
      upsert: false,
      cacheControl: '3600',
    });

  if (error) {
    params.onProgress?.('error');
    assertNoSupabaseError(error, 'uploadPendingSubmissionImage');
  }

  const storedPath = data?.path || storagePath;
  params.onProgress?.('uploaded');
  return {
    bucket: STORAGE_BUCKETS.PENDING_SUBMISSIONS,
    storagePath: storedPath,
  };
}

/**
 * Generates a short-lived signed URL for authorized admin review of a private
 * `pending-submissions` image. Never exposes private bucket files via public URLs.
 */
export async function createPendingSubmissionSignedUrl(
  client: SupabaseClient | null,
  storagePath: string,
  expiresInSeconds = 300
): Promise<string> {
  const db = requireSupabaseClient(client, 'createPendingSubmissionSignedUrl');

  if (!isRelativeStoragePath(storagePath)) {
    throw new SupabaseRepositoryError(
      'createPendingSubmissionSignedUrl',
      'Invalid private storage path requested for signed URL generation.',
      { code: 'INVALID_STORAGE_PATH' }
    );
  }

  const clampedExpiry = Math.min(900, Math.max(60, Math.floor(expiresInSeconds)));
  const { data, error } = await db.storage
    .from(STORAGE_BUCKETS.PENDING_SUBMISSIONS)
    .createSignedUrl(storagePath.trim(), clampedExpiry);

  assertNoSupabaseError(error, 'createPendingSubmissionSignedUrl');

  if (!data?.signedUrl) {
    throw new SupabaseRepositoryError(
      'createPendingSubmissionSignedUrl',
      'Supabase Storage did not return a signed URL for the requested private file.'
    );
  }

  return data.signedUrl;
}
