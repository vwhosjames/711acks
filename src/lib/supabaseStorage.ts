export const STORAGE_BUCKETS = {
  PENDING_SUBMISSIONS: 'pending-submissions',
  PUBLISHED_DRINKS: 'published-drinks',
  VERIFIED_PRODUCTS: 'verified-products',
  PRIVATE_ADMIN_BACKUPS: 'private-admin-backups',
} as const;

export type StorageBucketName =
  (typeof STORAGE_BUCKETS)[keyof typeof STORAGE_BUCKETS];

export const ALLOWED_IMAGE_MIME_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp',
] as const;

export const ALLOWED_BACKUP_MIME_TYPES = ['application/json'] as const;

export const MAX_IMAGE_FILE_SIZE_BYTES = 5 * 1024 * 1024; // 5 MB
export const MAX_BACKUP_FILE_SIZE_BYTES = 10 * 1024 * 1024; // 10 MB
export const MIN_IMAGE_DIMENSION_PX = 120;
export const MAX_IMAGE_DIMENSION_PX = 6000;

/**
 * Exact path regex enforced by 003_storage_setup.sql on `pending-submissions`
 * and generated by `buildPendingSubmissionStoragePath()`.
 */
export const PENDING_SUBMISSION_PATH_PATTERN =
  /^(finished-drink|suggested-product)\/[0-9]{4}-[0-9]{2}-[0-9]{2}\/[0-9a-f]{32}\.(jpg|png|webp)$/;

